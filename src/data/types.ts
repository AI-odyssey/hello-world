// 공용 타입. 책 하나 = Book, 장 하나 = Chapter, 절 하나 = Verse.
//
// MZ 버전 작성 원칙 (모든 장에 공통 적용):
// 1) 사건 자체(누가 무엇을 했는지, 순서, 결과, 숫자)는 절대 바꾸거나 지어내지 않는다.
// 2) 다만 "썰 풀어주는 화자"의 시선은 허용한다 — 본문 구조에 이미 있는 걸 짚어주는
//    관찰이나, 본문 자체의 강도 차이를 살린 리액션은 새 사실이 아니므로 OK.
//    반대로 본문에 없는 새로운 사건·이유·감정을 지어내는 건 금지.
// 3) 어미를 다양하게 쓴다 (~거든, ~더라고, ~대, ~다니까, ~는데, ~거지, ~잖아 등).
// 4) 슬랭을 여러 개 겹쳐 쌓지 않는다. 화자의 리액션은 절제해서, 포인트 되는 곳에만.

export type Verse = {
  n: number;
  para: number; // 같은 para 값끼리 묶어서 이어지는 한 문단으로 표시 (절 카드로 안 쪼갬)
  plain: string; // 쉬운 우리말 풀이 (원문 의미 기준)
  mz: string; // MZ(잘파) 스타일 의역
};

export type Chapter = {
  book: string;
  bookEn: string;
  chapter: number;
  title: string;
  verses: Verse[];
};
